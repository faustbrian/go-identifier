#!/usr/bin/env ruby
# Deterministic generation from reviewed, versioned upstream data, not the host
# toolchain's Unicode tables. Run from the repository root; no network access.
require 'digest'
require 'json'
require 'fileutils'

source = File.expand_path(ARGV.fetch(0))
pins = {
  'UnicodeData.txt' => '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86',
  'DerivedNormalizationProps.txt' => '8875dccee2bc1a7c1fe568a3b502a9e78c9e0495afd96b6568b4294d0ed1f7e1',
  'CaseFolding.txt' => '4e55acfdc32825a22e87670e9056a3bf94ad7c5400065778e9e10f8314372bcf',
  'PropList.txt' => '05672956317b6296bc2ec3d6cef1f6452b57ff4f2efc6dc55b0a19277d5fcfd1',
  'DerivedJoiningType.txt' => '2e0ed3733272299007cf0b76e84a8a653192d99a4429d2232fffcabccfd2d462',
  'NormalizationTest.txt' => '871238e37e3be0696ec2bd0891119a041b052da1a84485eda05a5438724b223e',
  'IdnaMappingTable.txt' => '402cbd285f1f952fcd0834b63541d54f69d3d8f1b8f8599bf71a1a14935f82c4',
  'IdnaTestV2.txt' => 'd668c4ea58d60fe04e6c011df98e0b317da6abaa1273d58f42b581eb0dd7adda',
  'punycode.go.txt' => '3e65858245f1a7d32e225aba714a305d3ef34496acb839956a7b15d1c7a34eb7'
}.freeze
pins.each do |name, digest|
  abort "unreviewed upstream input: #{name}" unless Digest::SHA256.file(File.join(source, name)).hexdigest == digest
end

def rows(path)
  File.readlines(path, encoding: 'UTF-8').filter_map do |line|
    text = line.split('#', 2).first.strip
    text.split(';').map(&:strip) unless text.empty?
  end
end
def interval(text)
  parts = text.split('..').map { |value| Integer(value, 16) }
  [parts.first, parts.last]
end
def mapping(text)
  text.split.map { |value| Integer(value, 16) }.pack('U*')
end
def literal(value)
  JSON.generate(value)
end

ud = rows(File.join(source, 'UnicodeData.txt'))
excluded = {}
rows(File.join(source, 'DerivedNormalizationProps.txt')).each do |row|
  next unless row[1] == 'Full_Composition_Exclusion'
  lo, hi = interval(row[0]); (lo..hi).each { |r| excluded[r] = true }
end
out = +"// Code generated by scripts/generate-unicode.rb; DO NOT EDIT.\n"
out << "// Unicode 15.1.0; see testdata/unicode151/provenance.json and licenses.\n\npackage identifier\n\n"
out << "var unicode151Decompositions = [...]unicodeDecomposition{\n"
compositions, classes, marks, bidi = [], [], [], []
ud.each do |row|
  r = Integer(row[0], 16)
  classes << [r, Integer(row[3])] unless row[3] == '0'
  marks << r if row[2].start_with?('M')
  bidi << [r, row[4]] unless row[4] == 'L'
  next if row[5].empty?
  parts = row[5].split
  compatibility = parts.first.start_with?('<')
  parts.shift if compatibility
  text = mapping(parts.join(' '))
  out << "{0x#{r.to_s(16)}, #{compatibility}, #{literal(text)}},\n"
  if !compatibility && parts.length == 2 && !excluded[r]
    a, b = parts.map { |v| Integer(v, 16) }
    compositions << [(a << 21) | b, r]
  end
end
out << "}\n\nvar unicode151Compositions = [...]unicodeComposition{\n"
compositions.sort.each { |key, r| out << "{#{key}, 0x#{r.to_s(16)}},\n" }
out << "}\n\nvar unicode151Classes = [...]unicodeClass{\n"
classes.each { |r, c| out << "{0x#{r.to_s(16)}, #{c}},\n" }
out << "}\n\nvar unicode151Marks = [...]rune{\n"
marks.each { |r| out << "0x#{r.to_s(16)},\n" }
out << "}\n\nvar unicode151Bidi = [...]unicodeBidi{\n"
bidi.each { |r, c| out << "{0x#{r.to_s(16)}, #{literal(c)}},\n" }
out << "}\n\nvar unicode151Folds = [...]unicodeMapping{\n"
rows(File.join(source, 'CaseFolding.txt')).select { |r| %w[C F].include?(r[1]) }.each do |row|
  out << "{0x#{row[0]}, #{literal(mapping(row[2]))}},\n"
end
out << "}\n\nvar unicode151Spaces = [...]unicodeRange{\n"
rows(File.join(source, 'PropList.txt')).select { |r| r[1] == 'White_Space' }.each do |row|
  lo, hi = interval(row[0]); out << "{#{lo}, #{hi}},\n"
end
out << "}\n\nvar unicode151Joining = [...]unicodeJoining{\n"
rows(File.join(source, 'DerivedJoiningType.txt')).sort_by { |r| interval(r[0]).first }.each do |row|
  lo, hi = interval(row[0]); out << "{#{lo}, #{hi}, #{literal(row[1])}},\n"
end
out << "}\n\nvar unicode151IDNA = [...]unicodeIDNA{\n"
previous = -1
rows(File.join(source, 'IdnaMappingTable.txt')).each do |row|
  lo, hi = interval(row[0]); abort 'IDNA table gap or overlap' unless lo == previous + 1
  previous = hi
  status = {'valid' => 0, 'mapped' => 1, 'ignored' => 2, 'deviation' => 3}.fetch(row[1], 4)
  out << "{#{lo}, #{hi}, #{status}, #{literal(mapping(row[2] || ''))}},\n"
end
abort 'incomplete IDNA table' unless previous == 0x10ffff
out << "}\n"
File.write('unicode151_tables.go', out)

puny = File.read(File.join(source, 'punycode.go.txt'))
puny.sub!('package idna', 'package identifier')
puny.sub!('func punyError(s string) error { return &labelError{s, code16("A3", "P4")} }', 'func punyError(_ string) error { return ErrNormalization }')
# Invalid U+FFFD is rejected by the fixed mapping table before encoding. Remove
# the host-Unicode-version branch, rather than inheriting Go's moving policy.
branch = "\t\tif unicode16 && r == 0xfffd {\n\t\t\treturn s, &labelError{s, \"A3\"}\n\t\t}\n"
abort 'upstream encoder changed' unless puny.include?(branch)
puny.sub!(branch, '')
%w[base damp initialBias initialN skew tmax tmin decode encode madd decodeDigit encodeDigit adapt].each do |name|
  puny.gsub!(/\b#{name}\b/, "puny#{name[0].upcase}#{name[1..]}")
end
puny.sub!(/\A.*?\n\n/m, "// Code generated by scripts/generate-unicode.rb; DO NOT EDIT.\n// Adapted from golang.org/x/net v0.59.0/idna/punycode.go; see provenance.json.\n\n")
File.write('punycode151.go', puny)

target = 'testdata/unicode151'
FileUtils.mkdir_p(target)
(pins.keys + %w[UNICODE-LICENSE.txt GO-LICENSE.txt]).each do |name|
  from, to = File.join(source, name), File.join(target, name)
  FileUtils.cp(from, to) unless File.exist?(to) && File.identical?(from, to)
end
manifest = {
  unicode_version: '15.1.0', unicode_source: 'https://www.unicode.org/Public/15.1.0/ucd/',
  idna_source: 'https://www.unicode.org/Public/idna/15.1.0/',
  punycode_source: 'golang.org/x/net@v0.59.0/idna/punycode.go', sha256: pins,
  command: 'ruby scripts/generate-unicode.rb testdata/unicode151 && gofmt -w unicode151_tables.go punycode151.go',
  patches: ['Repackage and prefix private codec symbols.', 'Replace input-bearing codec errors with ErrNormalization.', 'Remove host unicode16 U+FFFD branch; fixed IDNA table rejects U+FFFD before encoding.'],
  update: 'Review new data and checksums, run pinned official corpora, preserve the 15.1 backend for existing profiles; new semantics require new profile identity/version and collision-aware migration.'
}
File.write(File.join(target, 'provenance.json'), JSON.pretty_generate(manifest) + "\n")
